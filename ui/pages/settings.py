def initialize_session_state() -> None:
    """Initialize session state variables for settings page."""
    if "settings_modified" not in st.session_state:
        st.session_state.settings_modified = False
    if "settings_data" not in st.session_state:
        # Load current settings
        settings = Settings()
        st.session_state.settings_data = settings.model_dump()


def save_settings_to_file(settings_data: Dict[str, Any], filepath: str) -> bool:
    """
    Save settings to a JSON file.
    
    Args:
        settings_data: Settings dictionary
        filepath: Path to save file
        
    Returns:
        True if successful, False otherwise
    """
    try:
        with open(filepath, 'w') as f:
            json.dump(settings_data, f, indent=2)
        return True
    except Exception as e:
        st.error(f"Error saving settings: {str(e)}")
        return False


def load_settings_from_file(filepath: str) -> Optional[Dict[str, Any]]:
    """
    Load settings from a JSON file.
    
    Args:
        filepath: Path to settings file
        
    Returns:
        Settings dictionary or None if error
    """
    try:
        with open(filepath, 'r') as f:
            return json.load(f)
    except Exception as e:
        st.error(f"Error loading settings: {str(e)}")
        return None


def update_env_file(settings_data: Dict[str, Any]) -> bool:
    """
    Update .env file with new settings.
    
    Args:
        settings_data: Settings dictionary
        
    Returns:
        True if successful, False otherwise
    """
    try:
        env_path = Path(".env")
        
        # Read existing .env if it exists
        env_vars = {}
        if env_path.exists():
            with open(env_path, 'r') as f:
                for line in f:
                    line = line.strip()
                    if line and not line.startswith('#') and '=' in line:
                        key, value = line.split('=', 1)
                        env_vars[key.strip()] = value.strip()
        
        # Update with new settings
        env_mapping = {
            "openai_api_key": "OPENAI_API_KEY",
            "openrouter_api_key": "OPENROUTER_API_KEY",
            "voyage_api_key": "VOYAGE_API_KEY",
            "cohere_api_key": "COHERE_API_KEY",
            "default_llm_provider": "DEFAULT_LLM_PROVIDER",
            "default_model": "DEFAULT_MODEL",
            "openrouter_model": "OPENROUTER_MODEL",
            "temperature": "TEMPERATURE",
            "max_tokens": "MAX_TOKENS",
            "default_embedding_model": "DEFAULT_EMBEDDING_MODEL",
            "voyage_model": "VOYAGE_MODEL",
            "bge_model": "BGE_MODEL",
            "default_vector_db": "DEFAULT_VECTOR_DB",
            "qdrant_url": "QDRANT_URL",
            "qdrant_collection": "QDRANT_COLLECTION",
            "milvus_url": "MILVUS_URL",
            "milvus_collection": "MILVUS_COLLECTION",
            "chunk_size_min": "CHUNK_SIZE_MIN",
            "chunk_size_max": "CHUNK_SIZE_MAX",
            "chunk_overlap": "CHUNK_OVERLAP",
            "ner_mode": "NER_MODE",
            "gliner_model": "GLINER_MODEL",
            "spacy_model": "SPACY_MODEL",
            "search_mode": "SEARCH_MODE",
            "default_rag_strategy": "DEFAULT_RAG_STRATEGY",
            "enable_hyde": "ENABLE_HYDE",
            "enable_compression": "ENABLE_COMPRESSION",
            "srag_max_iterations": "SRAG_MAX_ITERATIONS",
            "srag_quality_threshold": "SRAG_QUALITY_THRESHOLD",
            "crag_relevance_threshold": "CRAG_RELEVANCE_THRESHOLD",
            "short_term_memory_size": "SHORT_TERM_MEMORY_SIZE",
            "enable_long_term_memory": "ENABLE_LONG_TERM_MEMORY",
        }
        
        for key, env_key in env_mapping.items():
            if key in settings_data:
                value = settings_data[key]
                # Convert boolean to string
                if isinstance(value, bool):
                    value = str(value).lower()
                env_vars[env_key] = str(value)
        
        # Write back to .env
        with open(env_path, 'w') as f:
            f.write("# Visual RAG Document Explorer Configuration\n")
            f.write("# Generated by Settings UI\n\n")
            
            # Group by category
            f.write("# ============= API Keys =============\n")
            for key in ["OPENAI_API_KEY", "OPENROUTER_API_KEY", "VOYAGE_API_KEY", "COHERE_API_KEY"]:
                if key in env_vars:
                    f.write(f"{key}={env_vars[key]}\n")
            
            f.write("\n# ============= LLM Settings =============\n")
            for key in ["DEFAULT_LLM_PROVIDER", "DEFAULT_MODEL", "OPENROUTER_MODEL", "TEMPERATURE", "MAX_TOKENS"]:
                if key in env_vars:
                    f.write(f"{key}={env_vars[key]}\n")
            
            f.write("\n# ============= Embedding Settings =============\n")
            for key in ["DEFAULT_EMBEDDING_MODEL", "VOYAGE_MODEL", "BGE_MODEL"]:
                if key in env_vars:
                    f.write(f"{key}={env_vars[key]}\n")
            
            f.write("\n# ============= Vector DB Settings =============\n")
            for key in ["DEFAULT_VECTOR_DB", "QDRANT_URL", "QDRANT_COLLECTION", "MILVUS_URL", "MILVUS_COLLECTION"]:
                if key in env_vars:
                    f.write(f"{key}={env_vars[key]}\n")
            
            f.write("\n# ============= Other Settings =============\n")
            for key, value in env_vars.items():
                if key not in ["OPENAI_API_KEY", "OPENROUTER_API_KEY", "VOYAGE_API_KEY", "COHERE_API_KEY",
                              "DEFAULT_LLM_PROVIDER", "DEFAULT_MODEL", "OPENROUTER_MODEL", "TEMPERATURE", "MAX_TOKENS",
                              "DEFAULT_EMBEDDING_MODEL", "VOYAGE_MODEL", "BGE_MODEL",
                              "DEFAULT_VECTOR_DB", "QDRANT_URL", "QDRANT_COLLECTION", "MILVUS_URL", "MILVUS_COLLECTION"]:
                    f.write(f"{key}={value}\n")
        
        return True
    except Exception as e:
        st.error(f"Error updating .env file: {str(e)}")
        return False


def render_llm_settings() -> Dict[str, Any]:
    """
    Render LLM provider settings section.
    
    Returns:
        Dictionary of LLM settings
    """
    st.subheader("🤖 LLM Provider Settings")
    
    settings = {}
    
    col1, col2 = st.columns(2)
    
    with col1:
        settings["default_llm_provider"] = st.selectbox(
            "Provider",
            options=["openai", "openrouter"],
            index=0 if st.session_state.settings_data.get("default_llm_provider") == "openai" else 1,
            help="Select the LLM provider to use"
        )
    
    with col2:
        if settings["default_llm_provider"] == "openai":
            settings["default_model"] = st.selectbox(
                "Model",
                options=["gpt-4o", "gpt-4o-mini", "gpt-4-turbo", "gpt-3.5-turbo"],
                index=0,
                help="OpenAI model to use"
            )
        else:
            settings["openrouter_model"] = st.selectbox(
                "Model",
                options=[
                    "anthropic/claude-sonnet-4",
                    "anthropic/claude-3.5-sonnet",
                    "anthropic/claude-3-opus",
                    "google/gemini-pro-1.5",
                    "meta-llama/llama-3.1-70b-instruct"
                ],
                index=0,
                help="OpenRouter model to use"
            )
    
    # API Keys
    if settings["default_llm_provider"] == "openai":
        settings["openai_api_key"] = st.text_input(
            "OpenAI API Key",
            value=st.session_state.settings_data.get("openai_api_key", ""),
            type="password",
            help="Your OpenAI API key"
        )
    else:
        settings["openrouter_api_key"] = st.text_input(
            "OpenRouter API Key",
            value=st.session_state.settings_data.get("openrouter_api_key", ""),
            type="password",
            help="Your OpenRouter API key"
        )
    
    # Generation parameters
    col1, col2 = st.columns(2)
    
    with col1:
        settings["temperature"] = st.slider(
            "Temperature",
            min_value=0.0,
            max_value=2.0,
            value=float(st.session_state.settings_data.get("temperature", 0.0)),
            step=0.1,
            help="Controls randomness in generation (0 = deterministic, 2 = very random)"
        )
    
    with col2:
        settings["max_tokens"] = st.slider(
            "Max Tokens",
            min_value=100,
            max_value=4000,
            value=int(st.session_state.settings_data.get("max_tokens", 2048)),
            step=100,
            help="Maximum number of tokens to generate"
        )
    
    return settings


