def main() -> None:
    """Main function for the Settings page."""
    st.set_page_config(
        page_title="Settings - Visual RAG",
        page_icon="⚙️",
        layout="wide"
    )
    
    # Initialize session state
    initialize_session_state()
    
    # Load settings
    settings = Settings()
    
    # Render sidebar
    system_status = {
        "vector_db_connected": True,
        "vector_db_type": settings.default_vector_db,
        "llm_provider": settings.default_llm_provider,
        "llm_model": settings.default_model
    }
    
    selected_page = render_sidebar(
        current_page="settings",
        system_status=system_status,
        stats=None
    )
    
    # Handle page navigation
    if selected_page != "settings":
        st.switch_page(f"ui/pages/{selected_page}.py")
    
    # Main content
    st.title("⚙️ Settings")
    st.markdown("Configure all aspects of the Visual RAG system")
    
    st.divider()
    
    # Collect all settings
    all_settings = {}
    
    # LLM Settings
    with st.expander("🤖 LLM Provider Settings", expanded=True):
        all_settings.update(render_llm_settings())
    
    # Embedding Settings
    with st.expander("🔢 Embedding Settings", expanded=False):
        all_settings.update(render_embedding_settings())
    
    # Vector DB Settings
    with st.expander("🗄️ Vector Database Settings", expanded=False):
        all_settings.update(render_vectordb_settings())
    
    # Chunking Settings
    with st.expander("✂️ Chunking Settings", expanded=False):
        all_settings.update(render_chunking_settings())
    
    # RAG Settings
    with st.expander("🎯 RAG Settings", expanded=False):
        all_settings.update(render_rag_settings())
    
    # NER Settings
    with st.expander("🏷️ NER Settings", expanded=False):
        all_settings.update(render_ner_settings())
    
    # Memory Settings
    with st.expander("🧠 Memory Settings", expanded=False):
        all_settings.update(render_memory_settings())
    
    st.divider()
    
    # Action buttons
    col1, col2, col3, col4 = st.columns(4)
    
    with col1:
        if st.button("💾 Apply Settings", type="primary", use_container_width=True):
            # Update session state
            st.session_state.settings_data.update(all_settings)
            
            # Update .env file
            if update_env_file(st.session_state.settings_data):
                st.success("✅ Settings applied successfully! Restart the application for changes to take effect.")
                st.session_state.settings_modified = False
            else:
                st.error("❌ Failed to apply settings")
    
    with col2:
        if st.button("📥 Save to File", use_container_width=True):
            # Save to JSON file
            save_path = st.text_input("Save path", value="settings_backup.json")
            if save_path:
                if save_settings_to_file(all_settings, save_path):
                    st.success(f"✅ Settings saved to {save_path}")
    
    with col3:
        if st.button("📤 Load from File", use_container_width=True):
            # Load from JSON file
            load_path = st.text_input("Load path", value="settings_backup.json")
            if load_path and Path(load_path).exists():
                loaded_settings = load_settings_from_file(load_path)
                if loaded_settings:
                    st.session_state.settings_data = loaded_settings
                    st.success(f"✅ Settings loaded from {load_path}")
                    st.rerun()
    
    with col4:
        if st.button("🔄 Reset to Defaults", use_container_width=True):
            # Reset to default settings
            default_settings = Settings()
            st.session_state.settings_data = default_settings.model_dump()
            st.success("✅ Settings reset to defaults")
            st.rerun()
    
    # Show current configuration summary
    st.divider()
    st.subheader("📋 Current Configuration Summary")
    
    summary_col1, summary_col2, summary_col3 = st.columns(3)
    
    with summary_col1:
        st.markdown("**LLM Configuration**")
        st.info(f"""
        Provider: {all_settings.get('default_llm_provider', 'N/A')}
        Model: {all_settings.get('default_model', all_settings.get('openrouter_model', 'N/A'))}
        Temperature: {all_settings.get('temperature', 'N/A')}
        """)
    
    with summary_col2:
        st.markdown("**Vector DB Configuration**")
        st.info(f"""
        Database: {all_settings.get('default_vector_db', 'N/A')}
        Embedding: {all_settings.get('default_embedding_model', 'N/A')}
        Search Mode: {all_settings.get('search_mode', 'N/A')}
        """)
    
    with summary_col3:
        st.markdown("**RAG Configuration**")
        st.info(f"""
        Strategy: {all_settings.get('default_rag_strategy', 'N/A')}
        HyDE: {'Enabled' if all_settings.get('enable_hyde', False) else 'Disabled'}
        Compression: {'Enabled' if all_settings.get('enable_compression', True) else 'Disabled'}
        """)


if __name__ == "__main__":
    main()
